import { addDays, formatDay, today } from "./dates";
import { controversyScore, featureLabel, split } from "./scoring";
import { fitModel, getRange, hasSeedVotes, type TakeWithCounts } from "./takes";

export interface WeeklyOptions {
  /** last day included (YYYY-MM-DD). Defaults to yesterday, so only finished days count. */
  weekEnding?: string;
  top?: number;
  /** takes with fewer decided votes than this are left out */
  minVotes?: number;
}

export interface WeeklyExport {
  from: string;
  to: string;
  takes: TakeWithCounts[];
  markdown: string;
}

export function renderWeekly(args: {
  from: string;
  to: string;
  takes: TakeWithCounts[];
  totalVotes: number;
  sampleData: boolean;
  splitters: string[];
}): string {
  const { from, to, takes } = args;
  const range = `${formatDay(from, { month: "short", day: "numeric" })} to ${formatDay(to, { month: "short", day: "numeric", year: "numeric" })}`;
  const lines: string[] = [];
  if (args.sampleData) {
    lines.push("> **Sample data.** Some or all of the votes behind these splits were generated by the seed script, not cast by readers. Do not publish these numbers. Run `npm run seed:clear-votes` once real voting starts.", "");
  }
  lines.push("## GTM Twitter", "", `The five takes that split GTM people the most this week (${range}), from ${args.totalVotes.toLocaleString("en-US")} votes on gtmtakes.here.`, "");
  if (takes.length === 0) lines.push("_No takes collected enough votes this week._", "");
  takes.forEach((t, i) => {
    const s = split(t.counts);
    const depends = t.counts.depends > 0 ? `, ${s.dependsPct}% said "it depends"` : "";
    lines.push(
      `${i + 1}. **"${t.statement}"**`,
      `   ${s.hotPct}% Hot / ${s.notPct}% Not (${s.total.toLocaleString("en-US")} votes${depends})`,
      `   Source: [@${t.author_handle} on X](${t.source_url})`,
      "",
    );
  });
  if (args.splitters.length) lines.push(`**What is splitting people:** ${args.splitters.join("; ")}.`, "");
  return lines.join("\n");
}

export async function buildWeekly(opts: WeeklyOptions = {}): Promise<WeeklyExport> {
  const to = opts.weekEnding ?? addDays(today(), -1);
  const from = addDays(to, -6);
  const minVotes = opts.minVotes ?? 1;
  const all = await getRange(from, to);
  const takes = all
    .filter((t) => t.counts.hot + t.counts.not >= minVotes)
    .sort((a, b) => controversyScore(b.counts) - controversyScore(a.counts) || a.id - b.id)
    .slice(0, opts.top ?? 5);
  const totalVotes = all.reduce((n, t) => n + t.counts.hot + t.counts.not + t.counts.depends, 0);
  const model = await fitModel();
  const splitters = [...model.patterns.values()]
    .filter((p) => p.nTakes >= 3 && p.lift > 0.02)
    .sort((a, b) => b.lift - a.lift)
    .slice(0, 3)
    .map((p) => `${featureLabel(p.feature)} (+${Math.round(p.lift * 100)} pts more divisive than average, ${p.nTakes} takes)`);
  const markdown = renderWeekly({ from, to, takes, totalVotes, sampleData: await hasSeedVotes(), splitters });
  return { from, to, takes, markdown };
}
